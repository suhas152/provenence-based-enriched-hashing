def seed_company_drive(conn):
    if conn.execute("SELECT 1 FROM Documents WHERE owner_id=?", (COMPANY_OWNER,)).fetchone():
        return
    ts = now()
    for folder, name, title, lines in PDFS:
        data = make_pdf(title, lines)
        conn.execute("INSERT INTO Documents (owner_id, folder, name, kind, data, size, updated_at) "
                     "VALUES (?,?,?,?,?,?,?)", (COMPANY_OWNER, folder, name, "pdf", data, len(data), ts))
    for folder, name, content in TEXTS:
        conn.execute("INSERT INTO Documents (owner_id, folder, name, kind, content, size, updated_at) "
                     "VALUES (?,?,?,?,?,?,?)",
                     (COMPANY_OWNER, folder, name, "text", content, len(content.encode()), ts))
