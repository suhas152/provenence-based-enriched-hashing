def make_pdf(title, lines):
    """Minimal single-page PDF (Helvetica), no external dependencies."""
    def esc(s):
        return s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")

    ops = ["0.15 0.35 0.75 rg", "0 800 595 42 re f",           # header band
           "BT", "1 1 1 rg", "/F2 13 Tf", "50 815 Td", f"({esc(COMPANY_NAME.upper())}  |  CONFIDENTIAL) Tj", "ET",
           "BT", "0 0 0 rg", "/F2 20 Tf", "50 760 Td", f"({esc(title)}) Tj",
           "/F1 11 Tf", "16 TL", "0 -14 Td"]
    ops += [f"({esc(line)}) '" for line in lines]
    ops += ["ET", "BT", "0.5 0.5 0.5 rg", "/F1 8 Tf", "50 30 Td",
            f"(Generated by the {esc(COMPANY_NAME)} document system. Access to this file is audit-logged.) Tj", "ET"]
    stream = "\n".join(ops).encode("latin-1", "replace")
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] "
        b"/Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>",
        b"<< /Length %d >>\nstream\n" % len(stream) + stream + b"\nendstream",
    ]
    out, offsets = bytearray(b"%PDF-1.4\n"), []
    for i, obj in enumerate(objects, 1):
        offsets.append(len(out))
        out += b"%d 0 obj\n" % i + obj + b"\nendobj\n"
    xref = len(out)
    out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(objects) + 1)
    out += b"".join(b"%010d 00000 n \n" % off for off in offsets)
    out += b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (len(objects) + 1, xref)
    return bytes(out)


